static inline uint16_t Crc16Update(uint16_t cur_crc, uint8_t byte) {
  uint8_t idx;
  uint8_t crc_hi = (uint8_t)(cur_crc >> 8u);
  uint8_t crc_lo = (uint8_t)(cur_crc & 0xFFu);

  idx = crc_lo ^ byte;
  crc_lo = crc_hi ^ AucCrcHi[idx];
  crc_hi = AucCrcLo[idx];

  return ((uint16_t)crc_hi << 8u) | crc_lo;
};

static ParseSt CmdProc(uint8_t cmd) {
  switch (cmd) {
    case 0x01:
      return kLen;

    case 0x02:
      return kCrcLo;

    case 0x03:
      return kCrcLo;

    case 0x04:
      return kCrcLo;

    default:
      return kHeader1;
  }
};

static void CrcProc(uint8_t cmd) {
  switch (cmd) {
    case 0x01:
      st.test_flag = 1;
      break;

    case 0x02:
      st.a2b_mon_flag = 1;
      break;

    case 0x03:
      st.uart_mon_flag = 1;
      break;

    case 0x04:
      st.cpu_load_mon_flag = 1;
      break;

    default:
      break;
  }
};

