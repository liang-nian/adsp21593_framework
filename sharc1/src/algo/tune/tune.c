void TuneRx(uint8_t byte) {
  static ParseSt state = kHeader1;
  static RxPacket packet;
  static uint8_t payload_idx = 0;
  static uint16_t crc_calc = 0xFFFF;
  static uint8_t crc_rx_low = 0;

  switch (state) {
    case kHeader1:
      if (byte == 0x5A) {
        state = kHeader2;
      }
      break;

    case kHeader2:
      if (byte == 0xA5) {
        state = kCmd;
        crc_calc = 0xFFFF;
      } else if (byte == 0x5A) {
        state = kHeader2;
      } else {
        state = kHeader1;
      }
      break;

    case kCmd:
      packet.cmd = byte;
      crc_calc = Crc16Update(crc_calc, byte);
      state = CmdProc(packet.cmd);
      break;

    case kLen:
      packet.len = byte;
      crc_calc = Crc16Update(crc_calc, byte);
      payload_idx = 0;
      if (packet.len > 0) state = kPayload;
      else state = kCrcLo;
      break;

    case kPayload:
      packet.payload[payload_idx++] = byte;
      crc_calc = Crc16Update(crc_calc, byte);

      if (payload_idx >= packet.len) {
        state = kCrcLo;
      }
      // Add timer cnt here, control in timer driver for 500 ms.
      break;

    case kCrcLo:
      crc_rx_low = byte;
      state = kCrcHi;
      break;

    case kCrcHi: {
      uint16_t crc_rx = (uint16_t)byte << 8 | crc_rx_low;

      if (crc_rx == crc_calc) {
        CrcProc(packet.cmd);
        TuneProc(packet.payload);
      }
      state = kHeader1;
      break;
    }

    default:
      state = kHeader1;
      break;
  }
};

void TuneTx(uint8_t cmd, uint8_t* data, uint32_t len) {
  uint32_t i;
  uint16_t crc16 = 0xFFFF;
  uint8_t len8;
  uint8_t crc_bytes[2];

  /* TuneRx accepts a 1-byte length only for command 0x01. Commands 0x02,
   * 0x03 and 0x04 are header + cmd + CRC. A 4-byte length does not match
   * either form, and neither does the host endianness of a uint32_t. */
  if (cmd == 0x01u) {
    if (len > 255u || (len > 0u && data == NULL)) {
      return;
    }
  }

  Uart0Wr(header, 2);
  Uart0Wr(&cmd, 1);
  crc16 = Crc16Update(crc16, cmd);

  if (cmd == 0x01u) {
    len8 = (uint8_t)len;
    Uart0Wr(&len8, 1u);
    crc16 = Crc16Update(crc16, len8);
    if (len > 0u) {
      Uart0Wr(data, len);
      for (i = 0u; i < len; ++i) {
        crc16 = Crc16Update(crc16, data[i]);
      }
    }
  }

  crc_bytes[0] = (uint8_t)(crc16 & 0xFFu);
  crc_bytes[1] = (uint8_t)(crc16 >> 8);
  Uart0Wr(crc_bytes, 2u);
};
